defmodule SymbrellaWeb.BrainReport do
  @moduledoc """
  On-demand textual Brain diagnostics, generated by the Phoenix server.

  This is intentionally independent of JavaScript, browser clipboard APIs, and
  Tailwind/esbuild, so it works on Termux even when frontend assets cannot be
  rebuilt. The current runtime snapshot and retained blackboard history are
  read at request time rather than copying HTML from the dashboard.
  """

  alias SymbrellaWeb.BrainRuntime
  alias SymbrellaWeb.Components.Brain.SocialCognition
  alias SymbrellaWeb.Region.Registry

  @max_events 100

  @spec resolve_region(term()) :: atom()
  def resolve_region(region) when is_binary(region) do
    Enum.find(Registry.keys(), :lifg, fn key -> Atom.to_string(key) == region end)
  end

  def resolve_region(region) when is_atom(region) do
    if region in Registry.keys(), do: region, else: :lifg
  end

  def resolve_region(_), do: :lifg

  @spec generate(atom(), keyword()) :: String.t()
  def generate(region, opts \\ []) do
    runtime = Keyword.get(opts, :runtime, BrainRuntime)
    captured_at = Keyword.get(opts, :captured_at, DateTime.utc_now())
    region = resolve_region(region)

    # Keep the same bounded 100-event horizon as BrainLive's in-memory feed.
    blackboard =
      runtime.blackboard_history(@max_events)
      |> List.wrap()

    wm_snapshot = runtime.wm_snapshot()

    sections = [
      {"Selected region", region},
      {"Cycle clock", runtime.cycle_snapshot()},
      {"Mood and neuromodulators", runtime.mood_snapshot()},
      {"Brain overview", runtime.brain_snapshot()},
      {"Introspection and self-model", runtime.self_model_snapshot()},
      {"Self-portrait", runtime.self_portrait_snapshot()},
      {"Working memory", wm_snapshot},
      {"Conversational attention", conversational_attention(wm_snapshot)},
      {"Selected region snapshot", runtime.region_snapshot(region)},
      {"Selected region process status", runtime.region_status(region)},
      {"All region process statuses", runtime.all_region_status()},
      {"Read-only Colony cognition (not neuron activation)", SocialCognition.latest(blackboard)},
      {"Blackboard history (up to 100 retained events, unfiltered)", blackboard}
    ]

    [
      "Symbrella - Complete Brain Diagnostics",
      "Captured UTC: #{DateTime.to_iso8601(captured_at)}",
      "Selected region: #{region}",
      "Blackboard event count: #{length(blackboard)}",
      "Source: live BrainRuntime snapshots and Brain.Blackboard history",
      "",
      Enum.map_join(sections, "\n\n", fn {title, value} ->
        "===== #{title} =====\n" <>
          inspect(value, pretty: true, width: 110, limit: :infinity, printable_limit: :infinity)
      end),
      ""
    ]
    |> Enum.join("\n")
  end
  # Same session-bound WM comprehension data used by the live Brain panel.
  # Not independent proof of an external fact or a global attention setting.
  defp conversational_attention({:ok, %{wm: items}}) when is_list(items) do
    case Enum.find(items, fn item ->
           payload = if is_map(item), do: Map.get(item, :payload, %{}), else: %{}
           is_map(payload) and Map.get(payload, :kind) == :comprehension_frame
         end) do
      %{payload: %{context: %{} = context}} ->
        context
        |> Map.take([:topic, :topic_source, :focus_transition,
          :temporal_reference, :attention, :verification, :updated_at_ms])
        |> Map.put(:wm_admission, :admitted)

      _ ->
        %{status: :no_conversational_attention}
    end
  end

  defp conversational_attention(_), do: %{status: :unavailable}
end
