defmodule Core.Semantic.ActionQuestions do
  @moduledoc """
  Question-to-participant binding for evidence-gated finite-present SVO events.

  The question identifies an exact actor/action or surface-action/patient.
  Answers are assembled from the event's stored participant slots, never
  extracted from its original sentence or generated by the LLM.

  We deliberately do not guess inflected verb lemmas in question parsing:
  forward questions supply the canonical relation ("draw"), while reverse
  questions match the attested surface predicate ("draws"). The "what did
  [actor] do?" form requests a recorded activity, not a hypothetical past
  event or an inferred "do" relation. Ambiguous activity and reverse
  matches fail closed at Hippocampal retrieval.
  """

  alias Core.Semantic.EpisodicEvents

  @spec parse(String.t()) ::
          {:forward, String.t(), String.t()} |
          {:reverse, String.t(), String.t()} |
          {:activity, String.t()} | nil
  def parse(text) when is_binary(text) do
    t = String.trim(text)

    cond do
      m = Regex.named_captures(
            ~r/^who (?<surface_predicate>[\p{L}]+) (?<patient>(?:the|a|an|my) [\p{L} '-]+)\?$/iu, t
          ) ->
        {:reverse, norm(m["surface_predicate"]), norm(m["patient"])}

      m = Regex.named_captures(
            ~r/^what (?:does|did) (?<entity>(?:the|a|an|my) [\p{L} '-]+?) do\?$/iu, t
          ) ->
        if nominal_actor?(m["entity"]),
          do: {:activity, EpisodicEvents.entity_key(m["entity"])},
          else: nil

      m = Regex.named_captures(
            ~r/^what (?:does|did) (?<entity>(?:the|a|an|my) [\p{L} '-]+?) (?<predicate>[\p{L}]+)\?$/iu, t
          ) ->
        if nominal_actor?(m["entity"]),
          do: {:forward, EpisodicEvents.entity_key(m["entity"]), norm(m["predicate"])},
          else: nil

      true ->
        nil
    end
  end

  def parse(_), do: nil

  @spec answer(map() | nil, :actor | :patient | :activity, map()) :: String.t() | nil
  def answer(
        %{status: "asserted", relation: "verb_" <> predicate,
          value: patient, participants: %{
            "actor" => actor, "predicate" => recorded_predicate,
            "surface_predicate" => surface_predicate, "patient" => recorded_patient,
            "tense" => tense
          }},
        role,
        constraints
      )
      when tense in ["present", "past"] and
           is_binary(actor) and is_binary(predicate) and is_binary(recorded_predicate) and
           is_binary(patient) and is_binary(recorded_patient) and
           is_binary(surface_predicate) and is_map(constraints) do
    valid? =
      predicate == recorded_predicate and patient == recorded_patient and
        Enum.all?(constraints, fn
          {:predicate, value} -> value == predicate
          {:surface_predicate, value} -> value == surface_predicate
          {:patient, value} -> value == patient
          _ -> false
        end)

    if valid? do
      case role do
        :actor -> sentence(actor)
        :patient -> sentence(patient)
        :activity -> sentence(surface_predicate <> " " <> patient)
        _ -> nil
      end
    end
  end

  def answer(_, _, _), do: nil

  defp sentence(value) when is_binary(value) do
    value = String.trim(value)

    if value == "" do
      nil
    else
      String.upcase(String.first(value)) <>
        String.slice(value, 1, String.length(value)) <> "."
    end
  end

  # A bounded noun phrase may contain modifiers and compound nouns, but not
  # an auxiliary, another determiner, a clause linker, or a prepositional
  # complement. Otherwise the permissive actor regex can swallow part of the
  # question predicate (e.g. "the artist do without") and invent a verb slot.
  # This is a conservative syntax boundary, not an independent POS analysis.
  @non_nominal_terms ~w(
    a an the do does did is are was were have has had
    can could will would shall should may might must
    without with at by for from in into of on onto over under
    until after before during while to than because if
    and or but
  )

  defp nominal_actor?(entity) when is_binary(entity) do
    case String.split(norm(entity), " ", trim: true) do
      [article | words] when article in ~w(the a an my) ->
        words != [] and Enum.all?(words, &(not (&1 in @non_nominal_terms)))

      _ ->
        false
    end
  end

  defp norm(text),
    do: text |> String.downcase() |> String.trim() |> String.replace(~r/\s+/u, " ")
end
